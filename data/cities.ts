export function getCityId(entry: { city: string; countryCode: string }): string {
  const slug = String(entry.city || '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  const cc = String(entry.countryCode || 'gl').trim().toLowerCase();
  return `${cc}-${slug}`;
}

