import { buildPdfDocument } from '../../lib/pdfGenerator';

export function downloadMemorandumPdf(params: {
  title: string;
  city: string;
  userEmail: string;
  planDisplay: string;
  metricsLines: string[];
  notes?: string;
  watermarkText?: string;
}): string {
  const dateStr = new Date().toISOString().slice(0, 10);
  const watermark = params.watermarkText || `Generated by AQARI TERMINAL - Loomora Studios - Licensed to ${params.userEmail} - ${dateStr}`;
  const safeName = params.title.replace(/[^a-z0-9_-]+/gi, '_');
  const filename = `${safeName}_AQARI_MEMO.pdf`;

  const lines = [
    '=== INSTITUTIONAL INVESTMENT MEMORANDUM ===',
    `Asset: ${params.title}`,
    `Market / Jurisdiction: ${params.city}`,
    `Licensed Account: ${params.userEmail} (${params.planDisplay})`,
    `Generated Date: ${new Date().toUTCString()}`,
    '',
    '=== UNDERWRITING METRICS & COVENANT SUMMARY ===',
    ...params.metricsLines,
    ...(params.notes ? ['', '=== ANALYST NOTES ===', params.notes] : []),
    '',
    '=== REGULATORY & LEGAL NOTICE ===',
    'Market data is indicative, synced daily from public sources (World Bank, DLD, ONS, JLL).',
    'Not financial, legal or tax advice. Always consult a licensed advisor.',
    'Refund Policy: 5-7 Day Refund Window ONLY (technical issue, <= 3 analyses, no PDF downloaded).',
  ];

  const pdfBytes = buildPdfDocument({
    title: 'AQARI TERMINAL | Institutional Memorandum',
    subtitle: `${params.title} — ${params.city}`,
    lines,
    watermark,
    footer: `Loomora Studios - AQARI TERMINAL | ${watermark}`,
  });

  const blob = new Blob([pdfBytes as unknown as BlobPart], { type: 'application/pdf' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 5000);

  return filename;
}
